// Generator for ALL of lunch-lerum's food icons - standalone pixel-art
// objects, no bowls - for the word-by-word dish icons in fetch.mjs
// (WORD_ICON_RULES). This now also draws the 15 icons that used to sit on a
// bowl in generate-icons.mjs (chicken = drumstick with bone, fish, salmon
// fillet, meatballs, meatloaf, sausage, pancake stack, pasta on a fork,
// pie slice, pot with lid, rice = onigiri, soup = steaming mug, taco,
// casserole = baking dish, generic = plate with fork and knife), and
// overwrites those PNGs. Don't re-run generate-icons.mjs for those 15 (it
// would bring the bowls back); it's still the source for chef, cheese,
// macintosh and people. Each is
// original 32x32 pixel art stored as an editable text grid ('#' = black),
// upscaled 4x to 128px and written as plain 8-bit RGB PNG (the format TRMNL
// renders - see weather-yr's README "1-bit PNG" note) by a tiny built-in
// PNG encoder, so no `sharp` is needed.
//
// Word -> icon examples: gröna/veg/spenat -> leaf, potatis -> potato,
// havre/bulgur -> grain, MEDELHAVs- -> wave, -bullar -> bun, sallad -> salad,
// soja/baljväxt -> bean, HEMgjort/HUSmanskost -> house, italiensk -> pizza,
// lingon/bär -> berries, broccoli, BLOMkål -> flower, sås -> gravy,
// SOLgul/SOLtorkad -> sun, lime -> lemon, tomat -> tomato, gurka ->
// cucumber, kaka -> cake, JULbord -> tree, rotfrukt -> carrot, MEDALJonger
// -> medal, vitlök -> garlic. "no-veg" (crossed-out carrot) marks a day
// with no vegetarian dish, where the meat dish is shown instead.
//
//   node plugins/lunch-lerum/generate-word-icons.mjs

